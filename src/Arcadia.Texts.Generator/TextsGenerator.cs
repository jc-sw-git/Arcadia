using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Arcadia.Texts.Generator;

/// <summary>
/// For every <c>*Texts.resx</c> of a project (an AdditionalFile, see <c>Directory.Build.targets</c>) a static class of
/// the same name in the namespace of its folder: a property per text without placeholders, a method per text with
/// placeholders whose parameters are the placeholders' names, in name order. Both read through <c>UiText</c>, the one helper that
/// fills texts and never throws.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class TextsGenerator : IIncrementalGenerator
{
    private static readonly Regex Placeholder = new(@"\{([A-Za-z][A-Za-z0-9]*)(?::[^{}]*)?\}", RegexOptions.CultureInvariant);

    private static readonly DiagnosticDescriptor BadKey = new(
        "ARCTXT01", "Text key is not a C# identifier", "The key '{0}' in {1} is not a C# identifier", "Arcadia.Texts",
        DiagnosticSeverity.Error, isEnabledByDefault: true);

    private static readonly DiagnosticDescriptor UnreadableFile = new(
        "ARCTXT02", "Texts file is not readable", "{0} is not a readable .resx file: {1}", "Arcadia.Texts",
        DiagnosticSeverity.Error, isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var files = context.AdditionalTextsProvider
            .Where(file => file.Path.EndsWith("Texts.resx", System.StringComparison.OrdinalIgnoreCase))
            .Combine(context.AnalyzerConfigOptionsProvider)
            .Select((pair, cancellation) =>
            {
                var options = pair.Right.GlobalOptions;
                options.TryGetValue("build_property.RootNamespace", out var rootNamespace);
                options.TryGetValue("build_property.ProjectDir", out var projectDir);
                options.TryGetValue("build_property.AssemblyName", out var assemblyName);
                return new TextsFile(pair.Left.Path, pair.Left.GetText(cancellation)?.ToString() ?? string.Empty,
                    rootNamespace ?? string.Empty, projectDir ?? string.Empty, assemblyName ?? string.Empty);
            });

        context.RegisterSourceOutput(files, Generate);
    }

    private static void Generate(SourceProductionContext context, TextsFile file)
    {
        var className = Path.GetFileNameWithoutExtension(file.Path);
        List<(string Key, string Value)> texts;
        try
        {
            texts = XDocument.Parse(file.Content).Root!.Elements("data")
                .Where(data => data.Attribute("type") is null)
                .Select(data => ((string)data.Attribute("name")!, (string?)data.Element("value") ?? string.Empty))
                .ToList();
        }
        catch (System.Exception ex) when (ex is System.Xml.XmlException or System.NullReferenceException)
        {
            context.ReportDiagnostic(Diagnostic.Create(UnreadableFile, Location.None, file.Path, ex.Message));
            return;
        }

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/> from " + Path.GetFileName(file.Path) + " by Arcadia.Texts.Generator");
        source.AppendLine("#nullable enable");
        source.AppendLine("namespace " + NamespaceOf(file) + ";");
        source.AppendLine();
        source.AppendLine("/// <summary>The texts of " + Path.GetFileName(file.Path) + ", read and filled through UiText.</summary>");
        source.AppendLine("public static partial class " + className);
        source.AppendLine("{");
        source.AppendLine("    /// <summary>Where the texts are read from; a test may swap it for one with a broken text.</summary>");
        source.AppendLine("    public static global::System.Resources.ResourceManager Resources { get; set; } =");
        source.AppendLine("        new(\"" + file.AssemblyName + "." + className + "\", typeof(" + className + ").Assembly);");
        foreach (var (key, value) in texts)
        {
            if (!SyntaxFacts.IsValidIdentifier(key))
            {
                context.ReportDiagnostic(Diagnostic.Create(BadKey, Location.None, key, Path.GetFileName(file.Path)));
                continue;
            }

            source.AppendLine();
            source.AppendLine("    /// <summary>" + System.Security.SecurityElement.Escape(value).Replace("\r", string.Empty).Replace("\n", "\n    /// ") + "</summary>");
            // Parameters in name order, not text order: a translation or rewording that moves a placeholder must not change
            // the method's signature and so swap the values of calls that pass them by position.
            var names = Placeholder.Matches(value).Cast<Match>().Select(match => match.Groups[1].Value).Distinct()
                .OrderBy(name => name, System.StringComparer.Ordinal).ToList();
            if (names.Count == 0)
            {
                source.AppendLine("    public static string " + key + " => global::Arcadia.Launchers.Abstractions.Texts.UiText.Get(Resources, \"" + key + "\");");
                continue;
            }

            var parameters = string.Join(", ", names.Select(name => "object? " + Identifier(name)));
            var arguments = string.Join(", ", names.Select(name => "(\"" + name + "\", " + Identifier(name) + ")"));
            source.AppendLine("    public static string " + key + "(" + parameters + ") =>");
            source.AppendLine("        global::Arcadia.Launchers.Abstractions.Texts.UiText.Fill(Resources, \"" + key + "\", " + arguments + ");");
        }

        source.AppendLine("}");
        context.AddSource(className + ".g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    private static string Identifier(string name) =>
        SyntaxFacts.GetKeywordKind(name) == SyntaxKind.None ? name : "@" + name;

    // The namespace of the file's folder, as for a class beside it: Steam/SteamTexts.resx in Arcadia.Launchers is in
    // Arcadia.Launchers.Steam.
    private static string NamespaceOf(TextsFile file)
    {
        var folder = Path.GetDirectoryName(Path.GetFullPath(file.Path)) ?? string.Empty;
        var projectDir = file.ProjectDir.Length == 0 ? folder : Path.GetFullPath(file.ProjectDir).TrimEnd('/', '\\');
        var relative = folder.Length > projectDir.Length && folder.StartsWith(projectDir, System.StringComparison.OrdinalIgnoreCase)
            ? folder.Substring(projectDir.Length).Trim('/', '\\').Replace('/', '.').Replace('\\', '.')
            : string.Empty;
        return relative.Length == 0 ? file.RootNamespace : file.RootNamespace + "." + relative;
    }

    private sealed class TextsFile(string path, string content, string rootNamespace, string projectDir, string assemblyName)
        : System.IEquatable<TextsFile>
    {
        public string Path { get; } = path;

        public string Content { get; } = content;

        public string RootNamespace { get; } = rootNamespace;

        public string ProjectDir { get; } = projectDir;

        public string AssemblyName { get; } = assemblyName;

        public bool Equals(TextsFile? other) =>
            other is not null && Path == other.Path && Content == other.Content && RootNamespace == other.RootNamespace
            && ProjectDir == other.ProjectDir && AssemblyName == other.AssemblyName;

        public override bool Equals(object? obj) => Equals(obj as TextsFile);

        public override int GetHashCode() => Path.GetHashCode() ^ Content.GetHashCode();
    }
}
